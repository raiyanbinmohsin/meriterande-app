export const slugOf = (term: string) =>
  term.toLowerCase().replace(/[åä]/g, "a").replace(/ö/g, "o").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export const termBySlug = (slug: string): Term | undefined => TERMS.find((t) => slugOf(t.term) === slug);
